export function areasForCounty(county: string) {
  const normalize = (value: string) =>
    value.trim().toLocaleLowerCase().replace(/[’‘]/g, "'");
  const key = Object.keys(KENYA_LOCATIONS).find(
    (name) => normalize(name) === normalize(county),
  );
  return key ? KENYA_LOCATIONS[key] : [];
}

export function allKenyaAreas() {
  return [...new Set(Object.values(KENYA_LOCATIONS).flat())].sort((a, b) => a.localeCompare(b));
}
